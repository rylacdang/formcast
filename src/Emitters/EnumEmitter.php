<?php

declare(strict_types=1);

namespace Rylacdang\Formcast\Emitters;

use BackedEnum;
use InvalidArgumentException;
use ReflectionClass;
use UnitEnum;

final class EnumEmitter
{
    /**
     * Emit a deterministic TypeScript const object + union type for a PHP enum.
     *
     * @param  class-string<UnitEnum>  $enumClass
     */
    public function emit(string $enumClass): string
    {
        if (! enum_exists($enumClass)) {
            throw new InvalidArgumentException("Class {$enumClass} is not a PHP enum.");
        }

        $reflection = new ReflectionClass($enumClass);
        $shortName = $reflection->getShortName();

        $lines = [
            '// Generated by Formcast. Do not edit.',
            '// Source: '.$enumClass,
            '',
            'export const '.$shortName.' = {',
        ];

        foreach ($enumClass::cases() as $case) {
            $value = $case instanceof BackedEnum
                ? $this->formatBackedValue($case->value)
                : $this->quote($case->name);

            $lines[] = '  '.$case->name.': '.$value.',';
        }

        $lines[] = '} as const;';
        $lines[] = '';
        $lines[] = 'export type '.$shortName.' = (typeof '.$shortName.')[keyof typeof '.$shortName.'];';

        return implode("\n", $lines)."\n";
    }

    private function formatBackedValue(int|string $value): string
    {
        return is_int($value) ? (string) $value : $this->quote($value);
    }

    private function quote(string $value): string
    {
        return "'".str_replace(['\\', "'"], ['\\\\', "\\'"], $value)."'";
    }
}
