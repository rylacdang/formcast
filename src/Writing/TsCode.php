<?php

declare(strict_types=1);

namespace Rylacdang\Formcast\Writing;

final class TsCode
{
    public static function quote(string $value): string
    {
        return "'".str_replace(
            ['\\', "'", "\r", "\n"],
            ['\\\\', "\\'", '\\r', '\\n'],
            $value,
        )."'";
    }

    /**
     * Convert a PHP FQCN into a namespace-mirrored relative TypeScript path.
     *
     * Example: `App\Http\Requests\StoreOrderRequest` -> `App/Http/Requests/StoreOrderRequest.ts`
     */
    public static function classToRelativePath(string $fqcn): string
    {
        return str_replace('\\', '/', ltrim($fqcn, '\\')).'.ts';
    }

    /**
     * Compute a POSIX relative import path (without `.ts`) between two output-relative files.
     */
    public static function relativeImportPath(string $fromRelativeFile, string $toRelativeFile): string
    {
        $fromParts = explode('/', dirname(str_replace('\\', '/', $fromRelativeFile)));
        $toWithoutExt = preg_replace('/\.ts$/', '', str_replace('\\', '/', $toRelativeFile)) ?? $toRelativeFile;
        $toParts = explode('/', $toWithoutExt);

        if ($fromParts === ['.']) {
            $fromParts = [];
        }

        while ($fromParts !== [] && $toParts !== [] && $fromParts[0] === $toParts[0]) {
            array_shift($fromParts);
            array_shift($toParts);
        }

        $up = str_repeat('../', count($fromParts));
        $joined = implode('/', $toParts);

        return $up === '' ? './'.$joined : $up.$joined;
    }

    /**
     * Format the sorted `const m = { ... } as const;` messages dictionary.
     *
     * @param  array<string, string>  $messages
     */
    public static function formatMessagesMap(array $messages): string
    {
        if ($messages === []) {
            return '';
        }

        ksort($messages, SORT_STRING);

        $lines = ['const m = {'];

        foreach ($messages as $key => $message) {
            $lines[] = '  '.self::quote($key).': '.self::quote($message).',';
        }

        $lines[] = '} as const;';

        return implode("\n", $lines);
    }

    /**
     * Assemble a complete, deterministic generated cast TypeScript file.
     *
     * @param  array<string, string>  $messages
     * @param  array<string, string>  $enumImports  Map of `ShortName => relativeImportPath`
     */
    public static function composeCastFile(
        string $sourcePath,
        string $exportName,
        string $schemaExpression,
        string $manifestBlock,
        string $typesBlock,
        array $messages = [],
        array $enumImports = [],
    ): string {
        $normalizedSource = str_replace('\\', '/', $sourcePath);

        $sections = [
            implode("\n", [
                '// Generated by Formcast. Do not edit.',
                '// Source: '.$normalizedSource,
                "import { z } from 'zod';",
                "import { defineCast, fc } from '@rylacdang/formcast';",
                ...self::formatEnumImports($enumImports),
            ]),
        ];

        $messagesBlock = self::formatMessagesMap($messages);

        if ($messagesBlock !== '') {
            $sections[] = $messagesBlock;
        }

        $sections[] = 'export const schema = '.$schemaExpression.';';
        $sections[] = $manifestBlock;
        $sections[] = $typesBlock."\nexport default {$exportName};";

        return implode("\n\n", $sections)."\n";
    }

    /**
     * Assemble a deterministic barrel `index.ts` re-exporting all generated casts.
     *
     * @param  array<string, string>  $casts  Map of `exportName => relativeFilePath`
     */
    public static function composeBarrelIndex(array $casts): string
    {
        ksort($casts, SORT_STRING);

        $lines = [
            '// Generated by Formcast. Do not edit.',
            '',
        ];

        if ($casts === []) {
            $lines[] = 'export {};';

            return implode("\n", $lines)."\n";
        }

        foreach ($casts as $exportName => $relativeFile) {
            $importPath = self::relativeImportPath('index.ts', $relativeFile);
            $lines[] = "export * as {$exportName} from ".self::quote($importPath).';';
        }

        return implode("\n", $lines)."\n";
    }

    /**
     * @param  array<string, string>  $enumImports
     * @return list<string>
     */
    private static function formatEnumImports(array $enumImports): array
    {
        ksort($enumImports, SORT_STRING);
        $lines = [];

        foreach ($enumImports as $shortName => $importPath) {
            $lines[] = "import { {$shortName} } from ".self::quote($importPath).';';
        }

        return $lines;
    }
}
