<?php

declare(strict_types=1);

use Rylacdang\Formcast\Writing\FileWriter;
use Rylacdang\Formcast\Writing\TsCode;

beforeEach(function (): void {
    $this->tempDir = sys_get_temp_dir().DIRECTORY_SEPARATOR.'formcast-writer-'.bin2hex(random_bytes(6));
});

afterEach(function (): void {
    if (! is_dir($this->tempDir)) {
        return;
    }

    $iterator = new RecursiveIteratorIterator(
        new RecursiveDirectoryIterator($this->tempDir, FilesystemIterator::SKIP_DOTS),
        RecursiveIteratorIterator::CHILD_FIRST,
    );

    foreach ($iterator as $item) {
        if ($item->isDir()) {
            rmdir($item->getPathname());
        } else {
            unlink($item->getPathname());
        }
    }

    rmdir($this->tempDir);
});

it('builds namespace-mirrored paths, relative imports, and deterministic cast files', function (): void {
    expect(TsCode::classToRelativePath('App\\Http\\Requests\\StoreOrderRequest'))
        ->toBe('App/Http/Requests/StoreOrderRequest.ts');

    expect(TsCode::relativeImportPath(
        'App/Http/Requests/StoreOrderRequest.ts',
        'App/Enums/PaymentMethod.ts',
    ))->toBe('../../Enums/PaymentMethod');

    $content = TsCode::composeCastFile(
        sourcePath: 'app/Http/Requests/StoreOrderRequest.php',
        exportName: 'StoreOrderRequest',
        schemaExpression: 'z.object({})',
        manifestBlock: "export const StoreOrderRequest = defineCast({ name: 'StoreOrderRequest', schema, serverFields: [], dependencies: {}, usedBy: [] });",
        typesBlock: "export type StoreOrderRequestInput = z.input<typeof schema>;\nexport type StoreOrderRequestOutput = z.output<typeof schema>;",
        messages: ['b.required' => 'B is required.', 'a.required' => 'A is required.'],
        enumImports: ['PaymentMethod' => '../../Enums/PaymentMethod'],
    );

    expect($content)->toContain("import { PaymentMethod } from '../../Enums/PaymentMethod';");
    expect(strpos($content, "'a.required'"))->toBeLessThan((int) strpos($content, "'b.required'"));
    expect($content)->toContain('export default StoreOrderRequest;');

    $barrel = TsCode::composeBarrelIndex([
        'StoreOrderRequest' => 'App/Http/Requests/StoreOrderRequest.ts',
        'AuthRegisterRequest' => 'App/Http/Requests/Auth/RegisterRequest.ts',
    ]);

    expect($barrel)->toBe(<<<'TS'
// Generated by Formcast. Do not edit.

export * as AuthRegisterRequest from './App/Http/Requests/Auth/RegisterRequest';
export * as StoreOrderRequest from './App/Http/Requests/StoreOrderRequest';

TS);
});

it('writes files, skips unchanged files via content hashes, cleans up stale files, and supports dry-run check mode', function (): void {
    $writer = new FileWriter;

    // 1. Initial write
    $first = $writer->write($this->tempDir, [
        'App/Http/Requests/StoreOrderRequest.ts' => "// order v1\n",
        'App/Http/Requests/OldRequest.ts' => "// old\n",
        'index.ts' => "// barrel v1\n",
    ]);

    expect($first->written)->toBe([
        'App/Http/Requests/OldRequest.ts',
        'App/Http/Requests/StoreOrderRequest.ts',
        'index.ts',
    ]);
    expect($first->unchanged)->toBe([]);
    expect($first->removed)->toBe([]);
    expect($first->hasChanges())->toBeTrue();
    expect(is_file($this->tempDir.DIRECTORY_SEPARATOR.'.formcast.json'))->toBeTrue();

    // 2. Dry-run check with identical content detects zero drift
    $checkClean = $writer->write($this->tempDir, [
        'App/Http/Requests/StoreOrderRequest.ts' => "// order v1\n",
        'App/Http/Requests/OldRequest.ts' => "// old\n",
        'index.ts' => "// barrel v1\n",
    ], dryRun: true);

    expect($checkClean->hasChanges())->toBeFalse();
    expect($checkClean->unchanged)->toHaveCount(3);

    // 3. Dry-run check with modified/removed files reports drift without touching disk
    $checkStale = $writer->write($this->tempDir, [
        'App/Http/Requests/StoreOrderRequest.ts' => "// order v2\n",
        'index.ts' => "// barrel v1\n",
    ], dryRun: true);

    expect($checkStale->hasChanges())->toBeTrue();
    expect($checkStale->written)->toBe(['App/Http/Requests/StoreOrderRequest.ts']);
    expect($checkStale->removed)->toBe(['App/Http/Requests/OldRequest.ts']);
    expect(is_file($this->tempDir.'/App/Http/Requests/OldRequest.ts'))->toBeTrue();

    // 4. Actual write updates changed file, keeps unchanged, and removes stale file
    $second = $writer->write($this->tempDir, [
        'App/Http/Requests/StoreOrderRequest.ts' => "// order v2\n",
        'index.ts' => "// barrel v1\n",
    ]);

    expect($second->written)->toBe(['App/Http/Requests/StoreOrderRequest.ts']);
    expect($second->unchanged)->toBe(['index.ts']);
    expect($second->removed)->toBe(['App/Http/Requests/OldRequest.ts']);
    expect(is_file($this->tempDir.'/App/Http/Requests/OldRequest.ts'))->toBeFalse();
});
